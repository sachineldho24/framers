import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

// Regenerate the website images and typed catalog after editing image-catalog.csv.
// The original print files in public/posterx are only read.
function parseCsv(text) {
  const rows = []; let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === '"') {
      if (quoted && text[i + 1] === '"') { field += '"'; i++; }
      else quoted = !quoted;
    } else if (c === "," && !quoted) { row.push(field); field = ""; }
    else if (c === "\n" && !quoted) { row.push(field.replace(/\r$/, "")); rows.push(row); row = []; field = ""; }
    else field += c;
  }
  if (field || row.length) { row.push(field.replace(/\r$/, "")); rows.push(row); }
  const headers = rows.shift();
  return rows.filter(row => row.length === headers.length).map(row => Object.fromEntries(headers.map((key, i) => [key, row[i]])));
}

const root = process.cwd();
const catalog = parseCsv((await fs.readFile(path.join(root, "public/posterx/image-catalog.csv"), "utf8")).replace(/^\uFEFF/, ""));
const capitals = new Map(["bmw", "ktm", "rs4", "cbr", "ns200", "rx100", "rc", "ls", "m3", "r15", "r6"].map(word => [word, word.toUpperCase()]));
const titleOf = subject => subject.split("-").map(word => capitals.get(word) ?? word[0].toUpperCase() + word.slice(1)).join(" ");
for (const dir of ["previews", "full"]) await fs.mkdir(path.join(root, "public/work-images", dir), { recursive: true });

const works = [];
for (const row of catalog) {
  if (path.basename(row.filename) !== row.filename) throw new Error(`Invalid artwork path: ${row.filename}`);
  const id = row.filename.replace(/\.[^.]+$/, "");
  const source = path.join(root, "public/posterx", row.filename);
  const image = `/work-images/previews/${id}.webp`;
  const fullImage = `/work-images/full/${id}.webp`;
  const preview = await sharp(source).rotate().resize({ width: 800, height: 1100, fit: "inside", withoutEnlargement: true }).webp({ quality: 84 }).toFile(path.join(root, "public", image));
  await sharp(source).rotate().resize({ width: 1600, height: 2200, fit: "inside", withoutEnlargement: true }).webp({ quality: 88 }).toFile(path.join(root, "public", fullImage));
  works.push({ id, title: titleOf(row.subject), category: row.category, image, fullImage, alt: row.description, width: preview.width, height: preview.height });
  if (works.length % 25 === 0) console.log(`Prepared ${works.length}/${catalog.length} artworks`);
}
await fs.writeFile(path.join(root, "src/lib/works-data.ts"), `// Generated by scripts/build-work-images.mjs from the visually reviewed artwork catalog.\nexport const WORK_ITEMS = ${JSON.stringify(works, null, 2)} as const;\n`);
console.log(`Prepared ${works.length} artwork previews, full views, and catalog entries.`);
